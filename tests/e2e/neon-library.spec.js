import { expect, test } from '@playwright/test';

test('neon account entry, live personal-space rail, mutation updates, guarded navigation and account isolation', async ({ page }, info) => {
  test.setTimeout(90000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('https://personal-art.example/**', route => route.fulfill({ contentType: 'image/webp', headers: { 'Access-Control-Allow-Origin': '*' }, path: 'client/public/images/night-listener-small.webp' }));
  await page.goto('/auth');
  await expect(page.getByRole('navigation', { name: 'Saved spaces' })).toHaveCount(0);
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toHaveCount(0);
  await expect(page.locator('.auth-panel')).toHaveCSS('opacity', '1');
  await page.evaluate(() => document.fonts.ready);
  expect(await page.locator('h1').evaluate(el => getComputedStyle(el).fontFamily)).toContain('Barlow Condensed');
  await page.getByLabel('Password', { exact: true }).fill('a private neon account testing phrase');
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text');
  await page.getByRole('button', { name: 'Hide password', exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'password');
  await page.screenshot({ path: `design/creative-verification/neon-signup-${info.project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Sign in', exact: true }).first().click();
  await expect(page.getByRole('heading', { name: /Back for/ })).toBeVisible();
  await page.screenshot({ path: `design/creative-verification/neon-login-${info.project.name}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByLabel('Your name').fill('Neon listener');
  await page.getByLabel('Email address').fill(`neon-${info.project.name}-${Date.now()}@example.com`);
  await page.getByLabel('Password', { exact: true }).fill('a private neon account testing phrase');
  await page.getByRole('button', { name: 'Create your account', exact: true }).click();
  const rail = page.getByRole('navigation', { name: 'Saved spaces' });
  await expect(rail).toBeVisible();
  await expect(rail).toHaveAttribute('aria-busy', 'false');
  await expect(rail.getByRole('link')).toHaveCount(0);
  await page.getByRole('link', { name: 'Create a space', exact: true }).click();
  await page.getByLabel('Space title').fill('Private night archive');
  await page.getByRole('tab', { name: 'Mood DNA', exact: true }).click();
  await page.getByRole('button', { name: 'Quiet', exact: true }).click();
  await page.getByRole('button', { name: 'Save space', exact: true }).click();
  const initialLink = rail.getByRole('link', { name: 'Open space: Private night archive', exact: true });
  await expect(initialLink).toBeVisible();
  await initialLink.click();
  await expect(initialLink).toHaveAttribute('aria-current', 'page');
  await page.getByRole('link', { name: 'Edit space', exact: true }).click();
  await page.getByLabel('Space title').fill('Midnight in pink');
  await page.getByRole('tab', { name: 'Images', exact: true }).click();
  await page.getByRole('button', { name: 'Add image', exact: true }).click();
  await page.getByLabel('Image URL 1', { exact: true }).fill('https://personal-art.example/night.webp');
  await page.getByLabel('Image description 1', { exact: true }).fill('A private night-train photo');
  await page.getByRole('button', { name: 'Save space', exact: true }).click();
  const renamed = rail.getByRole('link', { name: 'Open space: Midnight in pink', exact: true });
  await expect(renamed).toBeVisible();
  await expect(initialLink).toHaveCount(0);
  await expect.poll(() => renamed.locator('img').evaluate(image => image.naturalWidth)).toBeGreaterThan(0);
  await page.getByRole('tab', { name: 'Story', exact: true }).click();
  await page.getByLabel('Space title').fill('Unsaved private thought');
  await renamed.click();
  await expect(page.getByRole('dialog', { name: 'Leave your changes behind?' })).toBeVisible();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByLabel('Space title')).toHaveValue('Unsaved private thought');
  await renamed.click();
  await page.getByRole('button', { name: 'Discard and leave', exact: true }).click();
  await page.getByRole('link', { name: 'Worlds', exact: true }).click();
  await expect(page.locator('.archive-poster-copy')).toBeVisible();
  await page.screenshot({ path: `design/creative-verification/neon-home-${info.project.name}.png`, fullPage: true });
  // Real query navigation, with only an explicit upstream failure fixture.
  await page.route('**/api/music/search?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { code: 'MUSIC_PROVIDER_UNAVAILABLE', message: 'Provider failure deliberately injected for the home-search check.' } }) }));
  await page.getByLabel('START WITH A SOUND', { exact: true }).fill('night music');
  await page.getByRole('button', { name: 'Search music from home', exact: true }).click();
  await expect(page).toHaveURL(/\/signals\?q=night\+music$/);
  await expect(page.getByLabel('Search by song title or artist')).toHaveValue('night music');
  await expect(page.getByRole('alert')).toContainText('deliberately injected');
  await renamed.click();
  await page.getByRole('button', { name: 'Delete space', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete space', exact: true }).click();
  await expect(renamed).toHaveCount(0);
  // Leave a private space in the first account, then switch users in the same tab.
  await page.getByRole('link', { name: 'Create a space', exact: true }).click();
  await page.getByLabel('Space title').fill('Only the first account');
  await page.getByRole('tab', { name: 'Mood DNA', exact: true }).click();
  await page.getByRole('button', { name: 'Quiet', exact: true }).click();
  await page.getByRole('button', { name: 'Save space', exact: true }).click();
  await expect(rail.getByRole('link', { name: 'Open space: Only the first account' })).toBeVisible();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('complementary', { name: 'Your space library' })).toHaveCount(0);
  await page.getByLabel('Your name').fill('Another listener');
  await page.getByLabel('Email address').fill(`second-neon-${info.project.name}-${Date.now()}@example.com`);
  await page.getByLabel('Password', { exact: true }).fill('a different private neon testing phrase');
  await page.getByRole('button', { name: 'Create your account', exact: true }).click();
  await expect(rail).toBeVisible();
  await expect(rail).toHaveAttribute('aria-busy', 'false');
  await expect(rail.getByRole('link')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
